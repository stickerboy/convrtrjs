// Builds a Bootstrap Icons font with only the icons the site uses, and the CSS for them. Run by `npm run icons`, and
// before the Sass builds. It writes:
//   assets/fonts/bootstrap-icons.woff2   the font, with just those icons
//   scss/vendor/_bootstrap-icons.scss    its @font-face and a rule for each icon
// Both are committed, as main.css is. test/site/icons.test.js fails when they're out of date.
//
// Icons are found by name (bi-search) in templates, Markdown and scripts, and from the "icon" values in _data. An icon
// whose name only exists in a variable, such as the switcher's fallback, goes in ALWAYS.
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const pkg = path.join(root, "node_modules/bootstrap-icons");

export const FONT = "assets/fonts/bootstrap-icons.woff2";
export const SCSS = "scss/vendor/_bootstrap-icons.scss";

// Named only in a variable: assets/js/site/switcher.js falls back to file-earmark-text for pages outside a section
const ALWAYS = ["file-earmark-text"];

const SOURCES = ["_includes", "pages", "changelog", "assets/js"];
const SKIP = ["assets/js/vendor"];

// Every icon name in Bootstrap Icons, with its codepoint
export const iconMap = () => JSON.parse(fs.readFileSync(path.join(pkg, "font/bootstrap-icons.json"), "utf8"));

const files = () => [
    ...fs.readdirSync(root).filter((file) => /\.(njk|md)$/.test(file)),
    ...SOURCES.flatMap((dir) => fs.readdirSync(path.join(root, dir), { recursive: true })
        .map((file) => path.join(dir, file).replaceAll("\\", "/"))
        .filter((file) => /\.(njk|md|js|html)$/.test(file) && !SKIP.some((skip) => file.startsWith(skip)))),
];

/**
 * The names (without bi-) of every icon the site uses, sorted.
 */
export function findIcons() {
    const icons = new Set(ALWAYS);

    for (const file of files()) {
        for (const [, name] of fs.readFileSync(path.join(root, file), "utf8").matchAll(/(?<![\w-])bi-([a-z0-9]+(?:-[a-z0-9]+)*)/g)) {
            icons.add(name);
        }
    }
    for (const file of fs.readdirSync(path.join(root, "_data")).filter((file) => file.endsWith(".json"))) {
        for (const [, name] of fs.readFileSync(path.join(root, "_data", file), "utf8").matchAll(/"icon":\s*"([a-z0-9-]+)"/g)) {
            icons.add(name);
        }
    }

    return [...icons].sort();
}

/**
 * A short hash of the font, added to its URL so browsers fetch it again when the icons change.
 */
export const fontVersion = () => crypto.createHash("sha256").update(fs.readFileSync(path.join(root, FONT))).digest("hex").slice(0, 10);

async function build() {
    const { default: subsetFont } = await import("subset-font");
    const { version } = JSON.parse(fs.readFileSync(path.join(pkg, "package.json"), "utf8"));
    const map = iconMap();
    const icons = findIcons();
    // Names that look like icons but aren't, such as classes of our own; the test lists them
    const known = icons.filter((name) => name in map);

    const font = await subsetFont(fs.readFileSync(path.join(pkg, "font/fonts/bootstrap-icons.woff2")),
        String.fromCodePoint(...known.map((name) => map[name])), { targetFormat: "woff2" });
    fs.writeFileSync(path.join(root, FONT), font);

    const scss = `/*!
 * Bootstrap Icons v${version} (https://icons.getbootstrap.com/), only the icons Convrtr uses
 * Copyright 2019-2024 The Bootstrap Authors
 * Licensed under MIT (https://github.com/twbs/icons/blob/main/LICENSE)
 */
// Generated by scripts/icons.mjs: don't edit, run \`npm run icons\`. ${known.length} icons.

@font-face {
    font-display: block;
    font-family: "bootstrap-icons";
    src: url("../fonts/bootstrap-icons.woff2?v=${fontVersion()}") format("woff2");
}

.bi::before,
[class^="bi-"]::before,
[class*=" bi-"]::before {
    display: inline-block;
    font-family: bootstrap-icons !important;
    font-style: normal;
    font-weight: normal !important;
    font-variant: normal;
    text-transform: none;
    line-height: 1;
    vertical-align: -.125em;
    -webkit-font-smoothing: antialiased;
    -moz-osx-font-smoothing: grayscale;
}

${known.map((name) => `.bi-${name}::before { content: "\\${map[name].toString(16)}"; }`).join("\n")}
`;
    fs.writeFileSync(path.join(root, SCSS), scss.replace(/\n/g, "\r\n"));

    const unknown = icons.filter((name) => !(name in map));
    console.log(`[icons] ${known.length} icons, ${font.length} bytes${unknown.length ? ` (not icons: ${unknown.join(", ")})` : ""}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    await build();
}
